"""Spot-check: generate_fixtures.py positions every PII-bearing element with explicit inline CSS
and writes the label box to match by construction. This test catches any box-model surprise that
reasoning might have missed, by actually rendering a sample of fixtures in real Chromium and
comparing the label boxes against real getBoundingClientRect() measurements — not just trusting
the arithmetic."""

from __future__ import annotations

import json
from pathlib import Path

import pytest
from playwright.sync_api import sync_playwright

CORPUS_ROOT = Path(__file__).resolve().parents[1] / "corpus"
CORPUS_DEV = CORPUS_ROOT / "dev"
CORPUS_HELDOUT = CORPUS_ROOT / "heldout"
LABELS_DIR = Path(__file__).resolve().parents[1] / "labels"


def _screen_dir(screen_id: str) -> Path:
    """A screen_id's corpus directory lives under whichever split
    `generate_fixtures.py`'s `is_heldout()` assigned it to — check both rather than assuming dev,
    the same way `corpus/labels.py`'s own validator does."""
    dev_path = CORPUS_DEV / screen_id
    return dev_path if dev_path.exists() else CORPUS_HELDOUT / screen_id


def _all_screen_ids() -> list[str]:
    ids = []
    for root in (CORPUS_DEV, CORPUS_HELDOUT):
        if root.exists():
            ids.extend(p.name for p in root.iterdir() if p.is_dir())
    return sorted(ids)


# Every fixture (dev AND held-out — this checks rendered-box correctness, not detection results,
# so there is no held-out-discipline reason to skip it) with a real DOM-addressable value element.
# Every `canvas-*` fixture is excluded — its value is drawn on a <canvas>, which has no DOM box to
# measure; its label box is documented as an approximation in its own notes field for exactly this
# reason.
SAMPLE_SCREEN_IDS = [s for s in _all_screen_ids() if not s.startswith("canvas-")]


def _label_boxes(screen_id: str) -> list[tuple[str, list[int]]]:
    label = json.loads((LABELS_DIR / f"{screen_id}.json").read_text())
    # Only items with a DOM element id we can look up: PASSWORD/OTP/CARD_* use <input id="...">,
    # everything else generated by field_html() uses a <div id="...">. The canary item and the
    # NONE-labelled hard-negative box always correspond to the fixture's one visible value field.
    return [(item["entity"], item["box"]) for item in label["items"] if item["entity"] != "UNKNOWN_SENSITIVE"]


@pytest.mark.parametrize("screen_id", SAMPLE_SCREEN_IDS)
def test_label_boxes_match_real_rendered_positions(screen_id: str) -> None:
    page_path = _screen_dir(screen_id) / "page" / "index.html"
    if not page_path.exists():
        pytest.skip(f"{screen_id} fixture not generated yet")

    boxes = _label_boxes(screen_id)
    assert boxes, f"{screen_id} has no non-canary label items to check"

    with sync_playwright() as p:
        browser = p.chromium.launch(headless=False, args=["--headless=new"])
        page = browser.new_page(viewport={"width": 1280, "height": 720})
        page.goto(page_path.as_uri())

        # Every value-bearing element generated by field_html() or the forms builder has a
        # value_id used as its HTML id — recovered here by finding the one non-label,
        # non-heading element to measure the whole fixture's field(s) in DOM order.
        elements = page.locator("input, .field-value, [id]:not(.field-label)")
        count = elements.count()
        measured = []
        for i in range(count):
            box = elements.nth(i).bounding_box()
            if box:
                measured.append((round(box["x"]), round(box["y"]), round(box["width"]), round(box["height"])))

        browser.close()

    assert len(measured) >= len(boxes), (
        f"{screen_id}: expected at least {len(boxes)} measurable field elements, found {len(measured)}"
    )

    # Text labels are value-level (value_boxes.py): the value's own glyphs, which sit inside the
    # element that renders them — a phone number inside its sentence, an id inside its field.
    # Pictures and <input> values keep the element box. Either way the label must lie within a
    # rendered element, a few px of font-metric slack allowed; a box outside every element is a
    # box-model surprise (the off-by-(16,16) freetext-001 class of bug). Hard negatives (NONE) keep
    # their constructed element box, which may be wider than the text: its origin must match.
    slack = 3
    for entity, label_box in boxes:
        lx, ly, lw, lh = label_box
        if entity == "NONE":
            assert any(abs(m[0] - lx) <= 1 and abs(m[1] - ly) <= 1 for m in measured), (
                f"{screen_id} NONE: no rendered element at label origin {label_box[:2]}"
            )
            continue
        inside = [
            m
            for m in measured
            if m[0] - slack <= lx
            and m[1] - slack <= ly
            and lx + lw <= m[0] + m[2] + slack
            and ly + lh <= m[1] + m[3] + slack
        ]
        assert inside, f"{screen_id} {entity}: label box {label_box} lies inside no rendered element"
